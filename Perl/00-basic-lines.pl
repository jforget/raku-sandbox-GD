#!/usr/bin/env perl
# -*- encoding: utf-8; indent-tabs-mode: nil -*-
#
# Dessin avec des lignes basiques
# Drawing with basic lines
#

use v5.10;
use strict;
use warnings;
use GD;
use MIME::Base64;

my $name = '00-basic-lines';
my $width  = 120;
my $height =  50;
my $im     = GD::Image->new($width, $height);
my $white  = $im->colorAllocate(255, 255, 255);
my $black  = $im->colorAllocate(  0,   0,   0);
my $red    = $im->colorAllocate(255,   0,   0);
my $blue   = $im->colorAllocate(  0,   0, 255);

$im->line(10, 10, 100, 10, $red);
$im->line(10, 20, 100, 20, $blue);
$im->line(10, 30, 100, 40, $black);

open my $fh, '>', "$name.png"
    or die "opening PNG file: $!";
binmode $fh;
print $fh $im->png;
close $fh
    or die "closing PNG file: $!";

my $png =  MIME::Base64::encode($im->png);
$png =~ s/\n\z//;      # because the Raku module does not add a newline at the end
open $fh, '>', "$name.html"
    or die "opening HTML file: $!";
print $fh <<"EOF";
<html>
<head><title>Example of graphic file generated by GD</title></head>
<body>
<h1>External PNG file</h1>
<img src='$name.png'>
<h1>Embedded PNG data</h1>
<img src='data:image/png;base64,$png'>
</body>
</html>
EOF
close $fh
    or die "closing HTML file: $!";


__END__

=encoding utf8

=head1 NAME

00-basic-lines.pl - draw basic lines

=head1 SYNOPSIS

  perl    00-basic-lines.pl
  display 00-basic-lines.png
  firefox 00-basic-lines.html

=head1 DESCRIPTION

This program  generates a  PNG file  and an HTML  file with  a picture
showing  basic lines  (various colours,  single thickness,  no special
patterns such as dashed line or dotted line).

=head1 PARAMETERS

None.

=head1 PREREQUISITE

Modules C<GD> and C<MIME::Base64>.

