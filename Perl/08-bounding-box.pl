=encoding utf8

=head1 NAME

08-bounding-box.pl - drawing text using Free Type fonts, on a light grey background

=head1 SYNOPSIS

  perl    08-bounding-box.pl
  display 08-bounding-box.png
  firefox 08-bounding-box.html

=head1 DESCRIPTION

This program  generates a  PNG file  and an HTML  file with  a picture
showing various texts using Free Type (or True Type) fonts. Some texts
appear on  a light grey  background, reflecting the bounding  boxes of
the texts.

=head1 PARAMETERS

None.

=head1 PREREQUISITE

Modules C<GD> and C<MIME::Base64>.

=head1 PROBLEMS AND ISSUES

When drawing the bounding box with an opaque colour, you need a 3-step
process:

  @bounds = GD::Image->stringFT(...); # 1
  $im->rectangle(..., $grey_opaque);  # 2
  @bounds = $im->stringFT(...);       # 3

If, between  step 1 and  step 3, another  process installs a  new Free
Type font, the bounding box in step  3 can be quite different from the
bounding  box computed  in step  1.  The rectangle  in step  2 can  be
ill-fitting  to the  text in  step  3. This  is a  race condition.  To
prevent  this race  condition, you  should use  colours with  an alpha
channel.

  @bounds = $im->stringFT(...);       # 1
  $im->rectangle(..., $grey_transp);  # 2

